// stored `uiLang` wins if valid; otherwise map the browser's language, and
// fall back to English for anything not covered.
function i18nResolveLang(stored, navLang) {
  if (stored && I18N[stored]) return stored;
  const n = String(navLang || "").toLowerCase();
  if (n.startsWith("th")) return "th";
  if (n.startsWith("zh")) {
    return /(^|[-_])(tw|hk|mo|hant)/.test(n) ? "zh-TW" : "zh-CN";
  }
  if (n.startsWith("ja")) return "ja";
  if (n.startsWith("ko")) return "ko";
  if (n.startsWith("ru")) return "ru";
  if (n.startsWith("fr")) return "fr";
  if (n.startsWith("pt")) return "pt";
  return "en";
}

// look up `key` for `lang`, interpolating {name} placeholders from `params`.
// Falls back to English, then to the raw key, so a missing string is never
// blank.
function i18nT(lang, key, params) {
  const table = I18N[lang] || I18N.en;
  let s = table[key];
  if (s == null) s = I18N.en[key];
  if (s == null) return key;
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
  }
  return s;
}

// BCP-47 locale tag for Date#toLocaleDateString etc.
function i18nLocale(lang) {
  const entry = I18N_LANGS.find((l) => l.code === lang);
  return entry ? entry.locale : "en";
}

// set text / placeholder on every [data-i18n*] element under `root`.
// data-i18n -> textContent, data-i18n-placeholder -> placeholder attribute.
// Deliberately text-only (no innerHTML) so no markup ever rides in a string.
function applyI18n(root, lang) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = i18nT(lang, el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", i18nT(lang, el.getAttribute("data-i18n-placeholder")));
  });
}

