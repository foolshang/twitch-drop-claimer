/**
 * i18n.js - popup UI translations + a tiny lookup/apply helper.
 *
 * Loaded first (before shared.js) in the popup and the background script so
 * both can resolve the same UI language. Plain script, no module system -
 * exposes globals I18N_LANGS / I18N / i18nResolveLang / i18nT / i18nLocale /
 * applyI18n, matching how shared.js exposes its helpers.
 *
 * The selected language is stored in browser.storage.local as `uiLang`
 * (one of I18N_LANGS[].code). When it's unset, i18nResolveLang() picks from
 * the browser's own language, falling back to English.
 *
 * Every string is plain text - no HTML markup - so applyI18n() only ever
 * touches textContent / placeholder, never innerHTML.
 *
 * A few English/loan terms stay verbatim in every language ("Twitch",
 * "drop", "auto-watch", "All Campaigns", "inventory", "PowerShell", and the
 * literal Windows Settings menu path) - same mix the original Thai UI used,
 * and those are proper nouns / literal UI labels the user has to match on
 * screen anyway.
 */

